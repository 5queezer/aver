use std::env;
use std::ffi::OsStr;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest_dir = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").unwrap());
    let migrations_dir = manifest_dir
        .join("..")
        .join("..")
        .join("migrations")
        .canonicalize()
        .expect("workspace migrations directory must exist");
    let legacy_dir = manifest_dir
        .join("migrations-legacy")
        .canonicalize()
        .expect("crates/aver-core/migrations-legacy directory must exist");

    println!("cargo:rerun-if-changed={}", migrations_dir.display());
    println!("cargo:rerun-if-changed={}", legacy_dir.display());

    // Current chain: 0001..0008 plus the 0009 baseline (and anything after).
    let migrations = scan_sorted(&migrations_dir, 1);
    // Pre-baseline chain, applied only to stores whose user_version is in
    // 9..BASELINE_VERSION. Must start at 0009 and end at 0119 — the baseline
    // is a frozen snapshot of exactly that range.
    let legacy = scan_sorted(&legacy_dir, 9);
    let last_legacy = legacy.last().map(|(index, _, _)| *index);
    assert_eq!(
        last_legacy,
        Some(119),
        "legacy migration chain must end at 0119 (the frozen baseline); found {last_legacy:?}"
    );

    let mut generated = String::from(
        "// @generated by build.rs from workspace `migrations/` and \
         `crates/aver-core/migrations-legacy/` — do not edit.\n",
    );
    generated.push_str(&render_const("MIGRATIONS", &migrations));
    generated.push_str(&render_const("LEGACY_MIGRATIONS", &legacy));

    let out_dir = PathBuf::from(env::var_os("OUT_DIR").unwrap());
    fs::write(out_dir.join("migrations.rs"), generated).expect("write generated migrations.rs");
}

/// Read every `NNNN_<name>.sql` in `dir`, sorted by prefix, and verify the
/// prefixes are contiguous starting at `first`.
fn scan_sorted(dir: &Path, first: u32) -> Vec<(u32, String, PathBuf)> {
    let mut entries: Vec<(u32, String, PathBuf)> = fs::read_dir(dir)
        .expect("read migrations directory")
        .filter_map(|entry| {
            let entry = entry.expect("read migrations entry");
            let path = entry.path();
            if path.extension() != Some(OsStr::new("sql")) {
                return None;
            }
            let stem = path
                .file_stem()
                .expect("migration file has stem")
                .to_string_lossy()
                .into_owned();
            let (prefix, _) = stem.split_once('_').unwrap_or_else(|| {
                panic!("migration {stem}.sql must match NNNN_<name>.sql");
            });
            if prefix.len() != 4 || !prefix.chars().all(|c| c.is_ascii_digit()) {
                panic!("migration {stem}.sql prefix must be 4 ASCII digits");
            }
            let index: u32 = prefix
                .parse()
                .unwrap_or_else(|_| panic!("migration {stem}.sql has non-numeric prefix"));
            Some((index, stem, path))
        })
        .collect();

    entries.sort_by_key(|(index, _, _)| *index);

    for (i, (index, stem, _)) in entries.iter().enumerate() {
        let expected = first + i as u32;
        if *index != expected {
            panic!(
                "migration sequence has a gap or duplicate at {stem}.sql: \
                 expected prefix {expected:04}, found {index:04}"
            );
        }
    }

    entries
}

fn render_const(name: &str, entries: &[(u32, String, PathBuf)]) -> String {
    let mut out = format!("const {name}: &[(&str, &str)] = &[\n");
    for (_, stem, path) in entries {
        out.push_str("    (\n");
        out.push_str(&format!("        \"{stem}\",\n"));
        out.push_str(&format!(
            "        include_str!(r\"{}\"),\n",
            absolute_str(path)
        ));
        out.push_str("    ),\n");
    }
    out.push_str("];\n");
    out
}

fn absolute_str(path: &Path) -> String {
    path.to_str()
        .expect("migration paths must be valid UTF-8")
        .to_string()
}
